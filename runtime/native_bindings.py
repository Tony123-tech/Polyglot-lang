"""Generate the optional PyO3 scaffold for the 100-pillar capability surface.

The scaffold is deliberately *not* built by the normal test suite or by
``polyglot build``.  It exists so that every Python-side capability has a
corresponding ``#[pyfunction]`` declaration with an honest diagnostic.  For
capabilities that are implemented as host bridges, the generated binding
reports ``E006`` and directs callers to :func:`install_capability_bridge`.
For capabilities that cannot be implemented portably, it emits the same
rejection code as the Python path, preserving dual-backend parity.
"""

from __future__ import annotations

from pathlib import Path

from runtime.capabilities import CAPABILITIES, Capability

_PYMODULE = "polyglot_pillars"

_HEADER = """//! Generated by `runtime/native_bindings.py`. Do not edit by hand.
//!
//! This crate is an opt-in scaffold. It is not part of the stable `polyglot`
//! build and is not compiled by the default test suite.

use pyo3::exceptions::PyRuntimeError;
use pyo3::prelude::*;

fn pillar_error(code: &str, name: &str, reason: &str, span: Option<(usize, usize)>) -> PyErr {
    let location = match span {
        Some((start, end)) => format!(" (span {}..{})", start, end),
        None => String::new(),
    };
    PyRuntimeError::new_err(format!(
        "error[{}]: capability `{}` is not available{}\\n  reason: {}\\n  help: use the documented Python host bridge or an equivalent supported capability",
        code, name, location, reason
    ))
}
"""

# Rust's string escapes are a subset of Python's, but not identical to JSON's:
# e.g. `\\uXXXX` is not valid Rust (it must be `\\u{XXXX}`).  Escape explicitly.
_RUST_CHAR_ESCAPES = {
    "\\": "\\\\",
    '"': '\\"',
    "\n": "\\n",
    "\r": "\\r",
    "\t": "\\t",
    "\0": "\\0",
}


def _rust_string(value: str) -> str:
    """Return ``value`` as a valid Rust string literal.

    Backslashes, quotes and control characters are escaped; non-ASCII text is
    emitted verbatim so rustc sees a valid UTF-8 string literal.
    """
    parts = ['"']
    for char in value:
        escaped = _RUST_CHAR_ESCAPES.get(char)
        if escaped is not None:
            parts.append(escaped)
        elif ord(char) < 0x20 or ord(char) == 0x7F:
            parts.append(f"\\u{{{ord(char):x}}}")
        else:
            parts.append(char)
    parts.append('"')
    return "".join(parts)


def _binding(cap: Capability) -> str:
    code = cap.code if not cap.supported else "E006"
    reason = (
        cap.boundary
        if not cap.supported
        else "native execution uses the explicit host bridge; install it with runtime.capabilities.install_capability_bridge"
    )
    return (
        "#[pyfunction]\n"
        f"#[pyo3(name = {_rust_string(cap.name)})]\n"
        # Mirror the Python `reject()` contract: span is optional and defaults
        # to None, so calling the binding with no arguments still produces a
        # structured diagnostic rather than a TypeError.
        "#[pyo3(signature = (span = None))]\n"
        f"pub fn {cap.name}(\n"
        "    _py: Python<'_>,\n"
        "    span: Option<(usize, usize)>,\n"
        ") -> PyResult<()> {\n"
        f"    Err(pillar_error({_rust_string(code)}, {_rust_string(cap.name)}, "
        f"{_rust_string(reason)}, span))\n"
        "}\n"
    )


def generate_lib_rs() -> str:
    """Return a complete ``lib.rs`` with one ``#[pyfunction]`` per capability."""
    functions = "\n".join(_binding(cap) for cap in CAPABILITIES)
    registrations = "\n".join(
        f"    m.add_function(wrap_pyfunction!({cap.name}, m)?)?;"
        for cap in CAPABILITIES
    )
    return (
        _HEADER
        + "\n"
        + functions
        + "\n#[pymodule]\n"
        + f"fn {_PYMODULE}(m: &Bound<'_, PyModule>) -> PyResult<()> {{\n"
        + registrations
        + "\n    Ok(())\n}\n"
    )


def generate_cargo_toml() -> str:
    return f'''[package]
name = "{_PYMODULE}"
version = "0.1.0"
edition = "2021"

[lib]
name = "{_PYMODULE}"
crate-type = ["cdylib"]

[dependencies]
pyo3 = {{ version = "0.26", features = ["extension-module"] }}
'''


def write_crate(path: str | Path) -> Path:
    """Write the opt-in scaffold crate under ``path`` and return its root."""
    root = Path(path)
    (root / "src").mkdir(parents=True, exist_ok=True)
    (root / "Cargo.toml").write_text(generate_cargo_toml(), encoding="utf-8")
    (root / "src" / "lib.rs").write_text(generate_lib_rs(), encoding="utf-8")
    return root


__all__ = ["generate_cargo_toml", "generate_lib_rs", "write_crate"]
